#!/usr/bin/env node
/**
 * Bundles the planner's prompt files (src/lib/planner/prompts/*.md) into one module, so the Vercel function needs no
 * files at runtime and the system prompt is the same bytes on every call (prompt caching). Run it after editing a
 * prompt file; a unit test fails when the bundle is stale.
 *
 *   node scripts/planner-prompt.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

/** In the order they go into the system prompt. */
export const SOURCES = ['planner.md', 'coaching.md', 'check-in.md', 'plan-structure.md'];
export const DIR = 'src/lib/planner/prompts';
export const OUT = 'src/lib/planner/prompt-sources.generated.mjs';

export function render(root = '.') {
  const files = Object.fromEntries(SOURCES.map((f) => [f, readFileSync(`${root}/${DIR}/${f}`, 'utf8')]));
  const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 12);
  return `// Generated by scripts/planner-prompt.mjs from ${DIR}/*.md. Do not edit; edit the prompt files and run the script.\n` +
    `export const PROMPT_VERSION = ${JSON.stringify(version)};\n` +
    `export const SOURCES = ${JSON.stringify(files, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUT, render());
  console.log(`Wrote ${OUT}.`);
}
