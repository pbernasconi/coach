#!/usr/bin/env node
/**
 * Copies the coach's planning rules into the server planner, so the Vercel function needs no files at runtime and the
 * system prompt is the same bytes on every call (prompt caching). Run it after editing .claude/commands/plan.md,
 * plans/PLAN-STRUCTURE.md or scripts/plan-cloud/PROMPT.md; a unit test fails when the copy is stale.
 *
 *   node scripts/planner-prompt.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

export const SOURCES = ['.claude/commands/plan.md', 'plans/PLAN-STRUCTURE.md', 'scripts/plan-cloud/PROMPT.md'];
export const OUT = 'src/lib/planner/prompt-sources.generated.mjs';

export function render(root = '.') {
  const files = Object.fromEntries(SOURCES.map((f) => [f, readFileSync(`${root}/${f}`, 'utf8')]));
  const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 12);
  return `// Generated by scripts/planner-prompt.mjs from ${SOURCES.join(', ')}. Do not edit; run the script.\n` +
    `export const PROMPT_VERSION = ${JSON.stringify(version)};\n` +
    `export const SOURCES = ${JSON.stringify(files, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUT, render());
  console.log(`Wrote ${OUT}.`);
}
