#!/usr/bin/env node
/**
 * Render plans/YYYY-MM-DD.md from plans/YYYY-MM-DD.json.
 *
 * Why: the .md and .json used to be hand-written separately — double the tokens
 * and they could silently drift. The JSON is now the single source of truth and
 * the markdown is derived.
 *
 * Usage:
 *   node scripts/render-plan.mjs --plan plans/2026-07-20.json
 *   node scripts/render-plan.mjs --plan plans/2026-07-20.json --stdout   # preview
 *
 * Plan JSON fields consumed (beyond what the calendar script needs):
 *   title?        string   — heading suffix, e.g. "Lisbon travel week 🎂✈️"
 *   snapshotAtCreation { ctl, atl, tsb, weeklyTss, trend? }
 *   context?      string[] — bullets under "Snapshot"
 *   constraints?  string[] — bullets under "Calendar constraints"
 *   philosophy?   string[] — bullets under "Philosophy this week"
 *   completed?    [{ day, session, detail?, tss?, note? }]  — ✅ rows already done
 *   events[]      { title, start, end, timeZone?, workoutType, tss?, intensity?, why?, description }
 *   rest?         [{ day, reason }]  — 😴 rows with no calendar event
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative, basename } from 'node:path';
import { HOME_TZ } from './travel.mjs';

const PLANS_DIR = resolve('plans');
const args = process.argv.slice(2);
const getFlag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const PLAN_PATH = getFlag('--plan');
const TO_STDOUT = args.includes('--stdout');

if (!PLAN_PATH) {
  console.error('Usage: --plan plans/YYYY-MM-DD.json [--stdout]');
  process.exit(1);
}

// Keep file access inside plans/. This matters: --plan is supplied by an LLM
// whose context contains untrusted calendar text, and we write a sibling .md
// derived from this path — so it is not a trusted input.
// (The original guard also had a `resolve(rel) === resolved` clause; it's dead —
// only true when CWD is plans/, where it would wrongly reject a valid path.)
const resolved = resolve(PLAN_PATH);
if (relative(PLANS_DIR, resolved).startsWith('..')) {
  console.error(`--plan must resolve inside ${PLANS_DIR}`);
  process.exit(1);
}

const plan = JSON.parse(readFileSync(resolved, 'utf8'));
const DOW = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

function tzAbbr(iso, tz) {
  try {
    const parts = new Intl.DateTimeFormat('en-US', { timeZone: tz, timeZoneName: 'short' })
      .formatToParts(new Date(`${iso}Z`));
    return parts.find((p) => p.type === 'timeZoneName')?.value ?? tz;
  } catch { return tz; }
}

// start/end are local wall-clock strings ("2026-07-24T08:00:00") with an
// optional timeZone — format them as-written rather than converting.
function hhmm(iso) { return iso.slice(11, 16); }
function dayOf(iso) {
  const d = new Date(`${iso.slice(0, 10)}T00:00:00Z`);
  return `${DOW[d.getUTCDay()]} ${iso.slice(5, 10)}`;
}

const totalTss = (plan.events ?? []).reduce((s, e) => s + (Number(e.tss) || 0), 0)
  + (plan.completed ?? []).reduce((s, c) => s + (Number(c.tss) || 0), 0);

const md = [];
const heading = plan.title ? ` (${plan.title})` : '';
md.push(`# Training Plan — Week of ${plan.weekStart} → ${plan.weekEnd}${heading}`);
md.push('');
md.push(`_Generated by \`/plan\` · rendered from ${basename(resolved)} — edit the JSON, not this file._`);
md.push('');

const s = plan.snapshotAtCreation ?? {};
md.push('## Snapshot at creation');
if (s.ctl != null) {
  const mood = s.tsb > 5 ? '🟢 fresh' : s.tsb < -10 ? '🔴 deeply fatigued' : s.tsb < 0 ? '🟡 fatigued' : '⚪ neutral';
  md.push(`- **CTL** ${s.ctl} · **ATL** ${s.atl} · **TSB** ${s.tsb > 0 ? '+' : ''}${s.tsb} ${mood}`);
}
if (s.trend || s.weeklyTss != null) {
  md.push(`- ${[s.trend ? `7d trend: ${s.trend}` : null, s.weeklyTss != null ? `Weekly TSS (last 7d): ${s.weeklyTss}` : null].filter(Boolean).join(' · ')}`);
}
for (const c of plan.context ?? []) md.push(`- ${c}`);
md.push('');

if (plan.constraints?.length) {
  md.push('## Calendar constraints');
  for (const c of plan.constraints) md.push(`- ${c}`);
  md.push('');
}

md.push('## Plan');
md.push('| Day | Session | Time | Intensity | TSS | Why |');
md.push('|---|---|---|---|---|---|');

const rows = [];
for (const c of plan.completed ?? []) {
  rows.push({
    sort: c.day, day: `✅ ${dayOf(`${c.day}T00:00:00`)}`, session: c.session, time: 'done',
    intensity: c.detail ?? '—', tss: c.tss ?? '—', why: c.note ?? 'Completed',
  });
}
for (const e of plan.events ?? []) {
  const tz = e.timeZone ?? HOME_TZ;
  const abbr = tzAbbr(e.start, tz);
  rows.push({
    sort: e.start.slice(0, 10), day: dayOf(e.start), session: e.title,
    time: `${hhmm(e.start)}–${hhmm(e.end)} ${abbr}`,
    intensity: e.intensity ?? '—', tss: e.tss ?? '—', why: e.why ?? '',
  });
}
for (const r of plan.rest ?? []) {
  rows.push({ sort: r.day, day: dayOf(`${r.day}T00:00:00`), session: '😴 Rest', time: '—', intensity: '—', tss: 0, why: r.reason ?? '' });
}
rows.sort((a, b) => String(a.sort).localeCompare(String(b.sort)));
for (const r of rows) md.push(`| ${r.day} | ${r.session} | ${r.time} | ${r.intensity} | ${r.tss} | ${r.why} |`);
md.push('');
md.push(`**Week total ≈ ${Math.round(totalTss)} TSS**`);
md.push('');

if (plan.philosophy?.length) {
  md.push('## Philosophy this week');
  for (const p of plan.philosophy) md.push(`- ${p}`);
  md.push('');
}

md.push('## Check-in log');
md.push('_(update mid-week with actuals — `/check-in`)_');
const days = [...new Set(rows.map((r) => String(r.sort)))].sort();
for (const d of days) md.push(`- ${d}:`);
md.push('');

const out = md.join('\n');
if (TO_STDOUT) {
  console.log(out);
} else {
  const target = resolved.replace(/\.json$/, '.md');
  writeFileSync(target, out);
  console.log(`Rendered ${relative(process.cwd(), target)} (${out.length} chars, ${rows.length} rows, ~${Math.round(totalTss)} TSS).`);
}
